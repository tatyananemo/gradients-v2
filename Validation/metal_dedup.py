"""Guard exact source sharing against the accepted dead-code checkpoint.

Validation only: no shader source is generated by this module or by Xcode from this plan.
"""
import json
import hashlib
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
BASE = "12e1b51"


def clean(source):
    return re.sub(r"//[^\n]*|/\*.*?\*/", lambda m: "".join("\n" if c == "\n" else " " for c in m[0]), source, flags=re.S)


def function(source, name):
    stripped = clean(source)
    match = re.search(r"^\w+\s+" + re.escape(name) + r"\s*\([^;{}]*?\)\s*\{", stripped, re.M)
    assert match, name
    start = match.start()
    opening = stripped.index("{", start)
    depth, end = 1, opening + 1
    while depth:
        depth += (stripped[end] == "{") - (stripped[end] == "}")
        end += 1
    return start, end, source[start:end]


def original(root=ROOT):
    files = subprocess.check_output(["git", "ls-tree", "-r", "--name-only", BASE], cwd=root, text=True).splitlines()
    return {p: subprocess.check_output(["git", "show", f"{BASE}:{p}"], cwd=root).decode()
            for p in files if p.endswith(".swift") or p.startswith("ShaderSources/")}


def expected_sources(root=ROOT):
    plan = json.loads((root / "Validation/metal-dedup.json").read_text())
    assert plan["base_commit"] == BASE
    before = original(root)
    expected = dict(before)
    shared, edits = [], {}
    for record in plan["yellow_helpers"]:
        name, owner = record["name"], record["owner"]
        _, _, canonical = function(before[owner], name)
        shared.append(canonical)
        for path in record["modules"]:
            assert path.startswith("ShaderSources/Yellow")
            a, b, duplicate = function(before[path], name)
            tokenize = lambda s: re.findall(r"\w+|[^\s]", clean(s))
            assert tokenize(duplicate) == tokenize(canonical), f"Not identical: {path}::{name}"
            edits.setdefault(path, []).append((a, b, "using YellowShared::" + name + ";"))
    for path, replacements in edits.items():
        for a, b, replacement in sorted(replacements, reverse=True):
            expected[path] = expected[path][:a] + replacement + expected[path][b:]
    expected["ShaderSources/YellowShared.metal.source"] = (
        "// Exact helpers shared by the listed Yellow namespaces. Theme-specific readouts stay local.\n"
        "namespace YellowShared {\n\n" + "\n\n".join(shared) + "\n\n} // namespace YellowShared\n")
    expected["ShaderSources/CompositionInputs.xcfilelist"] = before["ShaderSources/CompositionInputs.xcfilelist"].replace(
        "$(SRCROOT)/ShaderSources/ContactFields.metal.source\n",
        "$(SRCROOT)/ShaderSources/ContactFields.metal.source\n$(SRCROOT)/ShaderSources/YellowShared.metal.source\n")
    # Authorized isolated source-include experiment. The original exact-sharing
    # proof remains intact; pin the block and all three literal substitutions.
    include = "ShaderSources/Shared/InteractionHistory.inc"
    block = (root / include).read_text()
    assert hashlib.sha256(block.encode()).hexdigest() == "c8cacc4671b790cc40aa342758928552eadcad3d78f09bb6e118b79003f0470f"
    blue = "ShaderSources/ApprovedBlue.metal.source"
    assert expected[blue].count(block) == 3
    expected[blue] = expected[blue].replace(block, '#include "Shared/InteractionHistory.inc"\n')
    expected[include] = block
    expected["ShaderSources/CompositionInputs.xcfilelist"] += "$(SRCROOT)/" + include + "\n"
    # Literal includes preserve the old function bodies; this is not the rejected
    # extraction into a function/result structure recorded by blue_prefix.
    prefix_path = "ShaderSources/Shared/PhysicalFields.inc"
    tail_path = "ShaderSources/Shared/BlueGeometryTail.inc"
    prefix, tail = (root / prefix_path).read_text(), (root / tail_path).read_text()
    assert hashlib.sha256(prefix.encode()).hexdigest() == "c1f77bec637e582df5fa9b04840e93dcf2945c5cd0987f284d60734f5ed2d8e2"
    assert hashlib.sha256(tail.encode()).hexdigest() == "abf2453a006349ff2c18d581d29e7d83fc64368dad1c6e89a8e4ddd1ca1ac97d"
    block = prefix + tail
    assert hashlib.sha256(block.encode()).hexdigest() == "8108b59cca2997b58fff9b3f4530d70f7aa89c57d3258e0f4ec9415439361e10"
    assert expected[blue].count(block) == 3
    expected[blue] = expected[blue].replace(block,
        '#include "Shared/PhysicalFields.inc"\n#include "Shared/BlueGeometryTail.inc"\n')
    contact = "ShaderSources/ContactFields.metal.source"
    assert expected[contact].count(prefix) == 1
    expected[contact] = expected[contact].replace(prefix, '#include "Shared/PhysicalFields.inc"\n')
    for path, text in [(prefix_path, prefix), (tail_path, tail)]:
        expected[path] = text
        expected["ShaderSources/CompositionInputs.xcfilelist"] += "$(SRCROOT)/" + path + "\n"
    assert plan["blue_prefix"] is None, "Blue extraction requires a separately verified source mapping"
    return expected


def verify(root=ROOT):
    expected = expected_sources(root)
    for path, text in expected.items():
        fixture = path in {"GradientInstallView.swift", "_22App.swift"} or path.startswith("Sources/")
        actual_path = root / "Validation/ReferenceV2" / path if fixture else root / path
        assert actual_path.read_text() == text, f"Unapproved change outside exact sharing: {path}"
    actual = {str(p.relative_to(root)) for p in (root / "ShaderSources").rglob("*") if p.suffix in {".source", ".inc"}}
    assert actual == {p for p in expected if p.endswith((".metal.source", ".inc"))}
    # The old deletion proof remains valid on its recorded checkpoint; current Swift is still frozen.
    assert (root / "Validation/metal-deletions.json").read_bytes() == subprocess.check_output(
        ["git", "show", BASE + ":Validation/metal-deletions.json"], cwd=root)
    return {"metal_exact_sharing_only": True, "swift_unchanged_since": "39b50ed"}


if __name__ == "__main__":
    print(verify())
